def _gate_pass_remarks_text(g: dict) -> str:
    """Combined remarks for print — gate pass + linked invoice notes."""
    parts = []
    for key in ("remarks", "purchase_notes", "sales_notes", "dispatch_remarks"):
        val = (g.get(key) or "").strip()
        if val and val not in parts:
            parts.append(val)
    return " | ".join(parts)


def _gate_pass_invoice_amount(g: dict) -> float:
    """Invoice net amount linked to this gate pass (purchase preferred, then sales)."""
    for key in ("purchase_invoice_total", "invoice_total"):
        try:
            amt = float(g.get(key) or 0)
        except (TypeError, ValueError):
            amt = 0.0
        if amt:
            return amt
    return 0.0


def _gate_pass_is_cash_sale(g: dict) -> bool:
    """True for SALE IN CASH / cash-sale outward gate passes (amounts print only then)."""
    if g.get("purchase_invoice_id") or g.get("purchase_invoice_no"):
        return False
    mode = (g.get("invoice_payment_mode") or "").strip().lower()
    if mode == "cash":
        return True
    party = (g.get("party_name") or g.get("customer_name") or "").strip().upper()
    return party in ("SALE IN CASH", "CASH SALE", "CASH SALES")


def _gate_pass_needs_full_page(g: dict, items: list) -> bool:
    """True when content will not fit cleanly on half A4 (~148mm) — print full page instead."""
    n = len(items or [])
    if n >= 5:
        return True
    # Approximate printed height in mm (header/party/meta/signatures ≈ 70–85mm fixed)
    height_mm = 78.0
    height_mm += n * 7.2
    if any(float(it.get("net_weight") or 0) for it in (items or [])):
        height_mm += 6.0  # Net Wt column + total weight line
    if _gate_pass_is_cash_sale(g):
        height_mm += 8.0 + n * 0.8  # Rate/Amount columns + amount totals
    inv_wt = float(g.get("invoice_weight_kg") or 0)
    phys = float(g.get("physical_weight_kg") or g.get("weight") or 0)
    if inv_wt or phys:
        height_mm += 14.0  # weight / variance block
    if _gate_pass_remarks_text(g):
        height_mm += 8.0
    if g.get("delivery_note_no") or g.get("grn_no"):
        height_mm += 6.0
    if g.get("driver_contact") or g.get("sales_invoice_no") or g.get("purchase_invoice_no"):
        height_mm += 4.0
    # Leave a small margin under 148mm so nothing clips
    return height_mm > 135.0


def _gate_pass_body(g: dict, items: list, *, duplicate: bool = False) -> str:
    """Build gate-pass HTML body (no page wrapper)."""
    inv_wt = float(g.get("invoice_weight_kg") or 0)
    phys = float(g.get("physical_weight_kg") or g.get("weight") or 0)
    var_kg = float(g.get("weight_variance_kg") or round(phys - inv_wt, 3))
    var_pct = float(g.get("weight_variance_pct") or 0)
    is_purchase = bool(g.get("purchase_invoice_id") or g.get("purchase_invoice_no"))
    show_amt = _gate_pass_is_cash_sale(g)
    extra = {
        "Type": (g.get("pass_type") or "").replace("_", " ").title(),
        "Vehicle": g.get("vehicle_no") or "—",
        "Driver": g.get("driver_name") or "—",
        "Weight Slip": g.get("weight_slip_no") or "—",
    }
    if g.get("driver_contact"):
        extra["Driver Contact"] = g.get("driver_contact")
    if g.get("sales_invoice_no"):
        extra["Sales Invoice"] = g["sales_invoice_no"]
    if g.get("purchase_invoice_no"):
        extra["Purchase Invoice"] = g["purchase_invoice_no"]
    party_phone = (g.get("party_phone") or g.get("customer_phone") or g.get("supplier_phone") or "").strip()
    if party_phone:
        extra["Party Contact"] = party_phone
    elif g.get("customer_id") or g.get("supplier_id"):
        extra["Party Contact"] = "—"

    title = "Gate Pass — DUPLICATE" if duplicate else ("Inward Gate Pass" if is_purchase else "Gate Pass")
    banner = '<div class="copy-banner gate-pass-dup-banner">DUPLICATE</div>' if duplicate else ""
    body = banner + _doc_header(
        title, g["document_no"], g["pass_date"], "Party", g.get("party_name"), extra,
        party_on_new_line=True,
        doc_time=g.get("pass_time") or g.get("created_at"),
    )
    if g.get("delivery_note_no"):
        body += _totals_block([f"<b>Delivery Note:</b> {escape(g['delivery_note_no'])}"])
    if g.get("grn_no"):
        body += _totals_block([f"<b>GRN:</b> {escape(g['grn_no'])}"])

    # Format line values on a shallow copy so dual print can reuse items
    lines = []
    has_wt = any(float(it.get("net_weight") or 0) for it in items)
    cols = [("item_code", "Code"), ("item_name", "Product"), ("quantity", "Qty")]
    if has_wt:
        cols.append(("net_weight", "Net Wt (kg)"))
    # Amounts only on SALE IN CASH / cash-sale gate passes (not credit / purchase)
    if show_amt:
        cols.extend([("rate", "Rate"), ("amount", "Amount")])
    total_qty = total_wt = total_amt = 0.0
    for src in items:
        it = dict(src)
        it["item_code"] = it.get("item_code") or "—"
        qty = float(it.get("quantity") or 0)
        nw = float(it.get("net_weight") or 0)
        it["quantity"] = f"{qty:,.2f}"
        it["net_weight"] = f"{nw:,.3f}"
        total_qty += qty
        total_wt += nw
        if show_amt:
            rate = float(src.get("rate") or 0)
            amt = float(src.get("amount") or 0)
            if not amt and rate and qty:
                amt = round(rate * qty, 2)
            it["rate"] = f"{rate:,.2f}"
            it["amount"] = f"{amt:,.2f}"
            total_amt += amt
        lines.append(it)
    if lines:
        body += _lines_table(lines, cols)
        summary = [f"<b>Total Quantity:</b> {total_qty:,.2f}"]
        if has_wt:
            summary.append(f"<b>Total Item Weight:</b> {total_wt:,.3f} kg")
        if show_amt:
            inv_total = _gate_pass_invoice_amount(g)
            summary.append(f"<b>Total Amount:</b> Rs. {total_amt:,.2f}")
            if inv_total and abs(inv_total - total_amt) > 0.05:
                summary.append(f"<b>Invoice Net:</b> Rs. {inv_total:,.2f}")
        body += _totals_block(summary)

    wt_lines = []
    if inv_wt:
        wt_lines.append(f"<b>Invoice Weight:</b> {inv_wt:,.3f} kg")
    if phys:
        wt_lines.append(f"<b>Physical Weight (Scale):</b> {phys:,.3f} kg")
    if inv_wt or phys:
        cls = "variance-ok" if abs(var_kg) < 0.5 else ("variance-warn" if abs(var_kg) < 5 else "variance-bad")
        wt_lines.append(f"<b>Variance:</b> <span class='{cls}'>{var_kg:+,.3f} kg ({var_pct:.2f}%)</span>")
    if wt_lines:
        body += _totals_block(wt_lines)

    remarks = _gate_pass_remarks_text(g)
    # Always print Remarks line on gate pass (especially purchase / inward)
    body += _totals_block([f"<b>Remarks:</b> {escape(remarks) if remarks else '—'}"])
    body += signature_block_html(doc_label="gate pass")
    return body


