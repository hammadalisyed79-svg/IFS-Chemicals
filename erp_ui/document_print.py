def system_generated_notice_html(doc_label: str = "document", extra_line: str = "") -> str:
    """Footer notice instead of signature lines on auto-printed ERP output."""
    label = (doc_label or "document").strip().lower()
    text = f"This is a system-generated {label}. It does not require any signature or stamp."
    extra = ""
    if extra_line:
        extra = f'<p class="sig-note">{escape(extra_line)}</p>'
    return (
        f'<div class="sys-generated-notice"><p>{escape(text)}</p></div>{extra}'
    )


def cash_signatures_html(
    prepared_name: str = "",
    *,
    extra_roles: tuple[tuple[str, str], ...] = (),
) -> str:
    """Signature block for cash / bank vouchers (optional extra roles e.g. Receiver)."""
    blank = "\u00a0"
    roles: list[tuple[str, str]] = [
        ("Prepared By", prepared_name),
        ("Checked By", ""),
        ("Approved By", ""),
    ]
    roles.extend(extra_roles)
    cells = []
    for label, show_name in roles:
        nm = escape((show_name or "").strip() or blank)
        cells.append(
            f'<div class="sig-cell"><div class="sig-prepared-name">{nm}</div>'
            f'<div class="sig-line"></div><div class="sig-role">{escape(label)}</div></div>'
        )
    sig_class = "signatures cash-sig-block" + (" sig-4" if len(roles) >= 4 else "")
    return f'<div class="{sig_class}">{"".join(cells)}</div>'


def posted_by_block_html(user_id=None) -> str:
    """JV / party transfer — show who posted the entry."""
    name = resolve_preparer_name(user_id)
    if not name:
        return ""
    return f'<p class="posted-by-line"><b>Posted by:</b> {escape(name)}</p>'


def signature_block_html(
    extra_line="",
    prepared_by=None,
    *,
    doc_label: str = "document",
    style: str = PRINT_STYLE_SYSTEM,
    user_id=None,
) -> str:
    uid = user_id if user_id is not None else prepared_by
    if style == PRINT_STYLE_CASH:
        return cash_signatures_html(resolve_preparer_name(uid), extra_roles=())
    if style == PRINT_STYLE_POSTED:
        return posted_by_block_html(uid)
    return system_generated_notice_html(doc_label, extra_line)


def is_cash_ledger_title(title: str) -> bool:
    t = (title or "").strip().lower()
    return t.startswith("cash book") or t.startswith("bank book")


def _doc_header(title, doc_no, doc_date, party_label, party_name, extra_meta=None, *, party_on_new_line=False, doc_time=None):
    extra = ""
    if extra_meta:
        # Avoid duplicating Time when Date/Time already includes it
        meta_items = {
            k: v for k, v in (extra_meta or {}).items()
            if str(k).strip().lower() not in ("time", "date / time", "datetime")
        }
        if meta_items:
            extra = '<div class="summary-box">' + "".join(
                f"<div><b>{escape(k)}:</b> {escape(str(v))}</div>" for k, v in meta_items.items()
            ) + "</div>"
    dt_disp = fmt_datetime(doc_date, doc_time)
    meta_parts = [
        f"<span><b>Document No:</b> {escape(doc_no)}</span>",
        f"<span><b>Date / Time:</b> {escape(dt_disp)}</span>",
    ]
    if not party_on_new_line:
        meta_parts.append(
            f"<span><b>{escape(party_label)}:</b> {escape(party_name or '—')}</span>"
        )
    party_block = ""
    if party_on_new_line:
        party_block = (
            f'<div class="party-block">'
            f'<div class="party-label">{escape(party_label)}</div>'
            f'<div class="party-name"><b>{escape(party_name or "—")}</b></div>'
            f"</div>"
        )
    return f"""
    {company_letterhead_html()}
    <h2>{escape(title)}</h2>
    <div class="meta">{"".join(meta_parts)}</div>
    {party_block}
    {extra}
    """


_LINE_COL_WEIGHTS = {
    "item_code": 12, "product_code": 12, "code": 11,
    "item_name": 36, "product_name": 36, "product": 34,
    "quantity": 9, "qty": 9, "unit": 7,
    "net_weight": 11, "rate": 9, "discount_pct": 8, "line_discount": 10,
    "amount": 11,
}


def _line_col_widths(cols) -> list[float]:
    weights = [_LINE_COL_WEIGHTS.get(c[0], 10) for c in cols]
    total = sum(weights) or 1.0
    return [100.0 * w / total for w in weights]


_NUM_LINE_COLS = frozenset({
    "quantity", "qty", "net_weight", "rate", "amount",
    "discount_pct", "line_discount", "tax_amount",
})


def _lines_table(items, cols):
    pcts = _line_col_widths(cols)
    colgroup = "".join(f'<col style="width:{p:.1f}%">' for p in pcts)
    thead = "".join(
        f"<th class='{'num' if c[0] in _NUM_LINE_COLS else ''}'>{escape(c[1])}</th>"
        for c in cols
    )
    rows = ""
    for it in items:
        rows += "<tr>" + "".join(
            f"<td class='{'num' if c[0] in _NUM_LINE_COLS else ('wrap' if c[0] in ('item_name', 'product_name') else '')}'>"
            f"{escape(str(it.get(c[0], '') or ''))}</td>"
            for c in cols
        ) + "</tr>"
    return (
        f"<table class='data lines-table'><colgroup>{colgroup}</colgroup>"
        f"<thead><tr>{thead}</tr></thead><tbody>{rows}</tbody></table>"
    )


def _invoice_line_cols_and_format(
    items: list, *, include_weight: bool = True, hide_rates: bool = False, rate_decimals: int = 2,
) -> tuple:
    """Build print columns; include Disc % / Disc when any line has discount."""
    from product_rates_legacy import _implied_line_discount_pct

    has_wt = include_weight and any(float(it.get("net_weight") or 0) for it in items)
    # Pre-resolve disc so FMYE-style amount < qty*rate lines count
    for it in items:
        qty = float(it.get("quantity") or 0)
        rate = float(it.get("rate") or 0)
        disc_amt = float(it.get("line_discount") or 0)
        disc_pct = float(it.get("discount_pct") or 0)
        if disc_pct <= 0.0001:
            disc_pct = _implied_line_discount_pct(qty, rate, disc_amt, it.get("amount"), 0)
        it["_disc_pct_resolved"] = disc_pct
        if disc_amt <= 0.0001 and disc_pct > 0.0001 and qty * rate > 0:
            it["_disc_amt_resolved"] = round(qty * rate * disc_pct / 100.0, 2)
        else:
            it["_disc_amt_resolved"] = disc_amt

    has_disc = (not hide_rates) and any(float(it.get("_disc_pct_resolved") or 0) > 0.005 for it in items)
    cols = [("item_name", "Product"), ("quantity", "Qty")]
    if has_wt:
        cols.append(("net_weight", "Net Wt (kg)"))
    if not hide_rates:
        cols.append(("rate", "Rate"))
        if has_disc:
            cols.append(("discount_pct", "Disc %"))
            cols.append(("line_discount", "Disc"))
        cols.append(("amount", "Amount"))

    rd = max(0, int(rate_decimals or 2))
    total_wt = 0.0
    for it in items:
        qty = float(it.get("quantity") or 0)
        rate = float(it.get("rate") or 0)
        disc_pct = float(it.get("_disc_pct_resolved") or 0)
        disc_amt = float(it.get("_disc_amt_resolved") or 0)
        it["quantity"] = f"{qty:,.2f}"
        it["rate"] = f"{rate:,.{rd}f}"
        it["amount"] = f"{float(it.get('amount', 0)):,.2f}"
        nw = float(it.get("net_weight") or 0)
        it["net_weight"] = f"{nw:,.3f}"
        total_wt += nw
        if has_disc:
            it["discount_pct"] = f"{disc_pct:,.2f}" if disc_pct > 0.005 else "—"
            it["line_discount"] = f"{disc_amt:,.2f}" if disc_amt > 0.005 else "—"
    return cols, total_wt, has_disc


def _totals_block(lines):
    return '<div class="summary-box">' + "".join(f"<div>{l}</div>" for l in lines) + "</div>"


def _wrap_doc(body, title, page_mode="half", user_id=None, *, footer_label=None, skip_footer=False):
    """page_mode 'half' = A4 portrait voucher (top 50%); 'full' = A4 portrait full page (invoices)."""
    footer = "" if skip_footer else document_footer_html(user_id, label=footer_label)
    if page_mode == "full":
        css = PRINT_CSS_PORTRAIT_FULL
        inner = f'<div class="doc-wrap">{body}{footer}</div>'
    else:
        css = PRINT_CSS_PORTRAIT_HALF
        inner = f"""<div class="half-page-sheet">{body}
    {footer}</div>
    <div class="half-page-cut">— cut line — bottom half blank (50% page) —</div>
    <div class="half-page-blank no-print">Bottom half of A4 left blank</div>"""
    return f"""<!DOCTYPE html><html><head><meta charset="utf-8"><title>{escape(title)}</title>
    {css}<script>function doPrint(){{window.print();}}</script></head><body>{inner}
    <p class="no-print"><button class="print-btn" onclick="doPrint()">Print</button></p></body></html>"""


