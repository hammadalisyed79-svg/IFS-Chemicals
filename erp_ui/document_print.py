def finance_vouchers_batch_html(entries):
    """Combine multiple cash/bank vouchers into one print job (one page each).

    entries: iterable of (vch_source, entry_id) or dicts with those keys / entry_source.
    """
    sheets = []
    titles = []
    for item in entries or []:
        if isinstance(item, dict):
            src = item.get("vch_source") or item.get("entry_source")
            eid = item.get("id") or item.get("entry_id")
        else:
            src, eid = item[0], item[1]
        if not src or eid is None:
            continue
        v = db.get_finance_voucher(src, int(eid))
        if not v:
            continue
        body, title, prepared_name, party_name = _finance_voucher_body(v)
        doc_no = v.get("document_no") or title
        titles.append(str(doc_no))
        if v.get("side") == "receipt":
            block = _receipt_voucher_dual_inner(body, prepared_name, party_name)
        else:
            block = _payment_voucher_half_inner(body, prepared_name, party_name)
        sheets.append(f'<div class="voucher-batch-page">{block}</div>')
    if not sheets:
        return ""
    doc_title = f"Cash Vouchers ({len(sheets)})"
    if len(titles) <= 4:
        doc_title = " + ".join(titles)
    css = PRINT_CSS_PORTRAIT_HALF.replace(
        "</style>",
        f"{_VOUCHER_PRINT_CSS_EXTRA}{_VOUCHER_BATCH_CSS}</style>",
    )
    inner = "\n".join(sheets)
    return f"""<!DOCTYPE html><html><head><meta charset="utf-8"><title>{escape(doc_title)}</title>
    {css}<script>function doPrint(){{window.print();}}</script></head>
    <body class="voucher-batch-body">{inner}
    <p class="no-print"><button class="print-btn" onclick="doPrint()">Print {len(sheets)} voucher(s)</button></p>
    </body></html>"""


def document_print_batch_toolbar(html, title, key_prefix="batch", *, preview_height=720):
    """Preview / download / open-print for a multi-document HTML bundle."""
    import streamlit as st
    import streamlit.components.v1 as components

    if not html:
        st.warning("No vouchers to print.")
        return
    with st.expander(f"Print Preview — {title}", expanded=True):
        components.html(html, height=preview_height, scrolling=True)
    c1, c2 = st.columns(2)
    safe = "".join(ch if ch.isalnum() or ch in "-_" else "_" for ch in title.lower())[:48]
    c1.download_button(
        "Download HTML", html.encode("utf-8"), f"{safe or 'vouchers'}.html", "text/html",
        key=f"{key_prefix}_h",
    )
    if c2.button("Open Print Dialog", key=f"{key_prefix}_pr", type="primary"):
        components.html(
            html.replace("</body>", "<script>window.onload=function(){window.print();}</script></body>"),
            height=0,
        )


def party_transfer_voucher_html(transfer_id):
    t = db.get_party_transfer(transfer_id)
    if not t:
        return ""
    title = "Party Transfer Voucher"
    try:
        from application.data_gateway import PARTY_TRANSFER_TYPES as PT
        label = PT.get(t["transfer_type"], t["transfer_type"])
    except Exception:
        label = t["transfer_type"]
    poster = document_poster_user_id(t)
    meta = {"Reference": t.get("reference_no") or "—"}
    if poster:
        pname = resolve_preparer_name(poster)
        if pname:
            meta["Posted By"] = pname
    body = _doc_header(
        title, t["document_no"], t["transfer_date"], "Transfer Type", label, meta,
        doc_time=t.get("created_at") or t.get("posted_at"),
    )
    body += f"<p><b>Description:</b> {escape(t.get('description') or '—')}</p>"
    body += _lines_table([{
        "from": f"{t.get('from_party_code','')} — {t.get('from_party_name','')}",
        "to": f"{t.get('to_party_code','')} — {t.get('to_party_name','')}",
        "amount": f"{float(t.get('amount', 0)):,.2f}",
    }], [("from", "Transfer From"), ("to", "Transfer To"), ("amount", "Amount (Rs.)")])
    body += _voucher_amount_box("Transfer Amount", t.get("amount", 0))
    body += signature_block_html(doc_label="voucher", style=PRINT_STYLE_POSTED, user_id=poster)
    return _wrap_doc(
        body, t["document_no"], user_id=poster, footer_label="Posted by",
    )


def expense_bill_html(bill_id):
    """Multi-expense bill: header + one row per expense head (no merged narration)."""
    b = db.get_expense_bill(bill_id)
    if not b:
        return ""
    poster = document_poster_user_id(b) or document_preparer_user_id(b)
    party_lbl = f"{b.get('party_code') or ''} — {b.get('party_name') or ''}".strip(" —")
    meta = {
        "Party Type": (b.get("party_type") or "").title(),
        "Settlement": (b.get("settlement") or "").title(),
        "Reference": b.get("reference_no") or "—",
    }
    if poster:
        pname = resolve_preparer_name(poster)
        if pname:
            meta["Posted By"] = pname
    body = _doc_header(
        "Expense Bill",
        b.get("document_no") or "",
        b.get("bill_date"),
        "Party",
        party_lbl or "—",
        meta,
        party_on_new_line=True,
        doc_time=b.get("created_at") or b.get("posted_at"),
    )
    note = (b.get("description") or "").strip()
    if note:
        body += f"<p><b>Bill note:</b> {escape(note)}</p>"
    rows = []
    for ln in b.get("lines") or []:
        code = ln.get("expense_code") or ""
        name = ln.get("expense_name") or ""
        narr = (ln.get("narration") or "").strip()
        rows.append({
            "account": f"{code} — {name}".strip(" —"),
            "narration": narr or "—",
            "amount": f"{float(ln.get('amount') or 0):,.2f}",
        })
    body += _lines_table(
        rows,
        [("account", "Expense Account"), ("narration", "Narration"), ("amount", "Amount (Rs.)")],
    )
    body += _voucher_amount_box("Bill Total", b.get("total_amount", 0))
    body += signature_block_html(doc_label="expense bill", style=PRINT_STYLE_POSTED, user_id=poster)
    return _wrap_doc(
        body, b.get("document_no") or "Expense Bill", user_id=poster, footer_label="Posted by",
        page_mode="full",
    )


