def _finance_voucher_body(v: dict) -> tuple[str, str, str, str]:
    """Build voucher HTML body; returns (body, title, prepared_name, party_name)."""
    pt = v.get("party_type")
    side = v.get("side")
    titles = {
        ("customer", "receipt"): "Customer Receipt Voucher",
        ("supplier", "payment"): "Supplier Payment Voucher",
        ("expense", "payment"): "Expense Payment Voucher",
    }
    title = titles.get((pt, side))
    if not title:
        if side == "receipt":
            title = f"{'Cash' if v['book'] == 'cash' else 'Bank'} Receipt Voucher"
        else:
            title = f"{'Cash' if v['book'] == 'cash' else 'Bank'} Payment Voucher"
    extra = {
        "Reference": v.get("reference_no") or "—",
        "Payment Mode": v.get("payment_mode") or "—",
    }
    if v.get("bank_account"):
        key = "Cash Account" if v.get("book") == "cash" else "Bank Account"
        extra[key] = v["bank_account"]
    if v.get("party_code"):
        extra["Party Code"] = v["party_code"]
    prep = document_preparer_user_id(v)
    prepared_name = resolve_preparer_name(prep) if prep else ""
    if prepared_name:
        extra["Prepared By"] = prepared_name

    party_name = (v.get("party_name") or "").strip()
    party_label = v.get("party_kind") or ("Received From" if side == "receipt" else "Paid To")
    # Prefer code + name for the prominent party block
    party_display = party_name
    if v.get("party_code") and party_name and str(v.get("party_code")) not in party_name:
        party_display = f"{v['party_code']} - {party_name}"
    if not party_display:
        party_display = "—"

    body = _doc_header(
        title, v.get("document_no", ""), v.get("txn_date"), party_label,
        party_display, extra,
        party_on_new_line=True,
        doc_time=v.get("created_at"),
    )
    narr = (v.get("description") or "").strip()
    if narr:
        body += f"<p><b>Narration:</b> {escape(narr)}</p>"
    amt_label = "Amount Received" if side == "receipt" else "Amount Paid"
    body += _voucher_amount_box(amt_label, v.get("amount", 0), v.get("payment_mode", ""))
    if v.get("party_balance") is not None and pt in ("customer", "supplier"):
        body += _totals_block([
            f"<b>Party ledger balance (after posting):</b> Rs. {float(v.get('party_balance', 0)):,.2f}",
        ])
    return body, title, prepared_name, party_name


