def document_print_toolbar(doc_type, doc_id, key_prefix="doc", vch_source=None, *, duplicate=False, dual=False, hide_rates=False):
    import streamlit as st
    import streamlit.components.v1 as components

    include_hdr = use_print_company_header_checkbox(key_prefix)
    with print_company_header_scope(include_hdr):
        if doc_type == "Party Transfer":
            html = party_transfer_voucher_html(doc_id)
        elif doc_type == "Expense Bill":
            html = expense_bill_html(doc_id)
        elif doc_type in ("Finance Voucher", "Customer Receipt", "Supplier Payment", "Expense Payment") and vch_source:
            html = finance_voucher_html(vch_source, doc_id)
        elif doc_type == "Receipt Voucher" and vch_source:
            html = finance_voucher_html(vch_source, doc_id)
        elif doc_type == "Payment Voucher" and vch_source:
            html = finance_voucher_html(vch_source, doc_id)
        elif doc_type == "Gate Pass":
            html = gate_pass_html(doc_id, duplicate=duplicate, dual=dual)
        elif doc_type == "Sales Order":
            html = sales_order_html(doc_id, hide_rates=bool(hide_rates))
        else:
            fn = PRINTERS.get(doc_type)
            if not fn:
                st.warning("Print format not available.")
                return
            html = fn(doc_id)
    if not html:
        st.warning("Document not found.")
        return

    preview_title = doc_type
    if dual:
        preview_title = f"{doc_type} (Original + Duplicate)"
    elif duplicate:
        preview_title = f"{doc_type} (Duplicate)"

    with st.expander(f"Print Preview — {preview_title}", expanded=True):
        # Long multi-line gate passes use full page — taller preview so all rows are visible
        if dual:
            preview_h = 900
        elif doc_type == "Gate Pass":
            preview_h = 780
        elif doc_type in (
            "Finance Voucher", "Receipt Voucher", "Payment Voucher",
            "Customer Receipt", "Supplier Payment", "Expense Payment",
        ):
            preview_h = 520
        else:
            preview_h = 560
        components.html(html, height=preview_h, scrolling=True)

    suffix = "_dual" if dual else ("_dup" if duplicate else "")
    fname = f"{doc_type.replace(' ', '_').lower()}_{doc_id}{suffix}"

    # Friendly PDF name: "Sale Order SO-0009 - Customer Name.pdf"
    party_name = ""
    pdf_label = doc_type
    try:
        if doc_type == "Sales Order":
            so = db.get_sales_order(int(doc_id))
            doc_no = ((so or {}).get("document_no") or "").strip()
            pdf_label = f"Sale Order {doc_no}".strip() if doc_no else "Sale Order"
            party_name = (so or {}).get("customer_name") or ""
        elif doc_type in ("Sales Invoice", "Sales Tax Invoice"):
            inv = db.get_sale(int(doc_id))
            doc_no = ((inv or {}).get("invoice_no") or (inv or {}).get("document_no") or "").strip()
            pdf_label = f"Sale Invoice {doc_no}".strip() if doc_no else "Sale Invoice"
            party_name = (inv or {}).get("customer_name") or ""
        elif doc_type == "Purchase Invoice":
            inv = db.get_purchase(int(doc_id)) if hasattr(db, "get_purchase") else None
            doc_no = ((inv or {}).get("invoice_no") or (inv or {}).get("document_no") or "").strip()
            pdf_label = f"Purchase Invoice {doc_no}".strip() if doc_no else "Purchase Invoice"
            party_name = (inv or {}).get("supplier_name") or ""
        elif doc_type == "Delivery Note" and hasattr(db, "get_delivery_note"):
            dn = db.get_delivery_note(int(doc_id))
            doc_no = ((dn or {}).get("document_no") or "").strip()
            pdf_label = f"Delivery Note {doc_no}".strip() if doc_no else "Delivery Note"
            party_name = (dn or {}).get("customer_name") or ""
    except Exception:
        party_name = ""
    from erp_ui.helpers import party_download_filename
    pdf_fname = party_download_filename(pdf_label, party_name, ext="pdf")
    if suffix:
        pdf_fname = pdf_fname.replace(".pdf", f"{suffix}.pdf")

    c1, c2, c3 = st.columns(3)
    c1.download_button("Print (HTML)", html.encode("utf-8"), f"{fname}.html", "text/html", key=f"{key_prefix}_h{suffix}")
    if c2.button("Open Print Dialog", key=f"{key_prefix}_pr{suffix}"):
        components.html(html.replace("</body>", "<script>window.onload=function(){window.print();}</script></body>"), height=0)
    pdf_bytes = None
    pdf_err = None
    try:
        if doc_type == "Sales Order" and not duplicate and not dual:
            pdf_bytes = sales_order_pdf_bytes(
                doc_id, hide_rates=bool(hide_rates), include_company=include_hdr,
            )
        elif doc_type in ("Sales Invoice", "Sales Tax Invoice") and not duplicate and not dual:
            pdf_bytes = sales_invoice_pdf_bytes(
                doc_id,
                tax_invoice=(doc_type == "Sales Tax Invoice"),
                include_company=include_hdr,
            )
        else:
            pdf_bytes = _scraped_html_pdf_bytes(
                html, preview_title, include_company=include_hdr,
            )
    except Exception as e:
        pdf_err = e
    if pdf_bytes:
        c3.download_button(
            "Download PDF",
            pdf_bytes,
            pdf_fname,
            "application/pdf",
            key=f"{key_prefix}_p{suffix}",
            type="primary",
        )
    else:
        c3.download_button(
            "Save HTML",
            html.encode("utf-8"),
            f"{fname}.html",
            "text/html",
            key=f"{key_prefix}_pf{suffix}",
        )
        if pdf_err:
            st.caption(f"PDF unavailable: {pdf_err}")

    # Gate Pass: one-click duplicate / dual print on the same screen
    if doc_type == "Gate Pass" and not duplicate and not dual:
        st.markdown("**Duplicate copy**")
        d1, d2 = st.columns(2)
        show_dup = d1.button("Print Duplicate", key=f"{key_prefix}_btn_dup", use_container_width=True)
        show_dual = d2.button(
            "Print Original + Duplicate (1 page)",
            key=f"{key_prefix}_btn_dual",
            use_container_width=True,
        )
        if show_dup:
            st.session_state[f"{key_prefix}_mode"] = "dup"
        if show_dual:
            st.session_state[f"{key_prefix}_mode"] = "dual"
        mode = st.session_state.get(f"{key_prefix}_mode")
        if mode == "dup":
            with print_company_header_scope(include_hdr):
                dup_html = gate_pass_html(doc_id, duplicate=True)
            st.success("Duplicate ready — use Open Print Dialog below, or the Print button inside the preview.")
            with st.expander("Print Preview — Gate Pass (Duplicate)", expanded=True):
                components.html(dup_html, height=560, scrolling=True)
            dd1, dd2, dd3 = st.columns(3)
            dd1.download_button(
                "Print Duplicate (HTML)", dup_html.encode("utf-8"),
                f"gate_pass_{doc_id}_dup.html", "text/html", key=f"{key_prefix}_dup_h",
            )
            if dd2.button("Open Print Dialog (Duplicate)", key=f"{key_prefix}_dup_pr"):
                components.html(
                    dup_html.replace("</body>", "<script>window.onload=function(){window.print();}</script></body>"),
                    height=0,
                )
            dd3.download_button(
                "Save Duplicate HTML", dup_html.encode("utf-8"),
                f"gate_pass_{doc_id}_dup.html", key=f"{key_prefix}_dup_pf",
            )
        elif mode == "dual":
            with print_company_header_scope(include_hdr):
                dual_html = gate_pass_html(doc_id, dual=True)
            st.success("Original + Duplicate on one A4 — use Open Print Dialog below.")
            with st.expander("Print Preview — Gate Pass (Original + Duplicate)", expanded=True):
                components.html(dual_html, height=720, scrolling=True)
            t1, t2, t3 = st.columns(3)
            t1.download_button(
                "Print Dual (HTML)", dual_html.encode("utf-8"),
                f"gate_pass_{doc_id}_dual.html", "text/html", key=f"{key_prefix}_dual_h",
            )
            if t2.button("Open Print Dialog (1 page)", key=f"{key_prefix}_dual_pr"):
                components.html(
                    dual_html.replace("</body>", "<script>window.onload=function(){window.print();}</script></body>"),
                    height=0,
                )
            t3.download_button(
                "Save Dual HTML", dual_html.encode("utf-8"),
                f"gate_pass_{doc_id}_dual.html", key=f"{key_prefix}_dual_pf",
            )
