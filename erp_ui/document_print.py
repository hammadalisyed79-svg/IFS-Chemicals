def amount_in_words(amount) -> str:
    """Convert number to Pakistani/Indian Rupees words (e.g. 1,25,430.50)."""
    try:
        n = float(amount or 0)
    except (TypeError, ValueError):
        return ""
    if n < 0:
        return "Minus " + amount_in_words(-n)

    ones = (
        "", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine",
        "Ten", "Eleven", "Twelve", "Thirteen", "Fourteen", "Fifteen", "Sixteen",
        "Seventeen", "Eighteen", "Nineteen",
    )
    tens = ("", "", "Twenty", "Thirty", "Forty", "Fifty", "Sixty", "Seventy", "Eighty", "Ninety")

    def _under_thousand(x: int) -> str:
        x = int(x)
        if x == 0:
            return ""
        if x < 20:
            return ones[x]
        if x < 100:
            return (tens[x // 10] + (" " + ones[x % 10] if x % 10 else "")).strip()
        return (ones[x // 100] + " Hundred" + (" " + _under_thousand(x % 100) if x % 100 else "")).strip()

    rupees = int(n)
    paisa = int(round((n - rupees) * 100))
    if paisa == 100:
        rupees += 1
        paisa = 0

    if rupees == 0:
        words = "Zero"
    else:
        parts = []
        crore = rupees // 10000000
        lakh = (rupees // 100000) % 100
        thousand = (rupees // 1000) % 100
        rest = rupees % 1000
        if crore:
            parts.append(_under_thousand(crore) + " Crore")
        if lakh:
            parts.append(_under_thousand(lakh) + " Lakh")
        if thousand:
            parts.append(_under_thousand(thousand) + " Thousand")
        if rest:
            parts.append(_under_thousand(rest))
        words = " ".join(parts)

    out = f"Rupees {words} Only"
    if paisa:
        out = f"Rupees {words} and {_under_thousand(paisa)} Paisa Only"
    return out


def document_footer_html(user_id=None, *, label=None) -> str:
    """Print footer: user name only (no timestamp / company)."""
    name = resolve_preparer_name(user_id)
    if not name:
        return ""
    if label is None:
        label = "Prepared by" if user_id else "Generated by"
    return f'<div class="footer">{escape(label)}: {escape(name)}</div>'


def document_preparer_user_id(record) -> int | None:
    """User id for footer — document creator, else approver if present."""
    if not record:
        return None
    return record.get("created_by") or record.get("approved_by")


def document_poster_user_id(record) -> int | None:
    """User who posted the voucher (JV posted_by, else creator)."""
    if not record:
        return None
    return record.get("posted_by") or record.get("created_by")


def resolve_preparer_name(user_id=None) -> str:
    """Display name for Prepared By — document creator, else current logged-in user."""
    if user_id:
        try:
            for u in db.get_users():
                if u.get("id") == user_id:
                    return (u.get("full_name") or u.get("username") or "").strip()
        except Exception:
            pass
    try:
        import streamlit as st
        u = st.session_state.get("user")
        if u:
            return (u.get("full_name") or u.get("username") or "").strip()
    except Exception:
        pass
    return ""


