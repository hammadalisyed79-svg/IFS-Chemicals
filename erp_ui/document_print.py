def sales_order_html(order_id, *, hide_rates: bool = False):
    inv = db.get_sales_order(order_id)
    if not inv:
        return ""
    extra = {
        "Status": _so_status_display(inv.get("status")),
        "Customer Code": inv.get("customer_code") or "—",
    }
    if inv.get("delivery_date"):
        extra["Delivery Date"] = inv["delivery_date"]
    town = (inv.get("dispatch_town") or "").strip()
    if not town:
        try:
            from erp_core.dispatch_planning import resolve_dispatch_to
            city = ""
            try:
                from database import get_connection
                with get_connection() as conn:
                    crow = conn.execute(
                        "SELECT city FROM customers WHERE id=?", (inv.get("customer_id"),)
                    ).fetchone()
                    if crow:
                        city = crow[0] or ""
            except Exception:
                city = ""
            dest = resolve_dispatch_to(inv.get("notes"), city)
            if dest and dest != "-":
                town = dest
        except Exception:
            pass
    if town:
        extra["Delivery Stop"] = town
    body = _doc_header(
        "Sales Order", inv["document_no"], inv["order_date"],
        "Customer", inv.get("customer_name"),
        extra,
        party_on_new_line=True,
        doc_time=inv.get("created_at"),
    )
    items = []
    for src in inv.get("items") or []:
        it = dict(src)
        name = it.get("product_name") or it.get("item_name") or ""
        code = (it.get("product_code") or "").strip()
        it["item_name"] = f"{code} — {name}" if code else name
        # Estimated net weight from standard weight × qty when no explicit net_weight
        if not float(it.get("net_weight") or 0):
            sw = float(it.get("standard_weight") or 0)
            qty = float(it.get("quantity") or 0)
            if sw > 0 and qty > 0:
                it["net_weight"] = round(sw * qty, 3)
        items.append(it)
    total_qty = sum(float(it.get("quantity") or 0) for it in items)
    cols, total_wt, has_disc = _invoice_line_cols_and_format(items, hide_rates=hide_rates)
    # Prefer unit column when present and no weight column crowding
    if any((it.get("unit") or "").strip() for it in items):
        # Insert Unit after Qty if not already showing weight-heavy layout
        names = [c[0] for c in cols]
        if "unit" not in names:
            qty_i = names.index("quantity") + 1 if "quantity" in names else 1
            cols = cols[:qty_i] + [("unit", "Unit")] + cols[qty_i:]
            for it in items:
                it["unit"] = (it.get("unit") or "").strip()
    body += _lines_table(items, cols)
    totals = []
    if not hide_rates:
        totals.append(f"<b>Subtotal:</b> Rs. {float(inv.get('subtotal', 0)):,.2f}")
        disc = float(inv.get("discount") or 0)
        tax = float(inv.get("tax") or 0)
        if disc > 0.005 or has_disc:
            totals.append(f"<b>{'Item Discount' if has_disc else 'Discount'}:</b> Rs. {disc:,.2f}")
        if tax > 0.005:
            totals.append(f"<b>Tax:</b> Rs. {tax:,.2f}")
        totals.append(f"<b>Total:</b> Rs. {float(inv.get('total', 0)):,.2f}")
    if total_qty > 0.0005:
        totals.append(f"<b>Total Quantity:</b> {total_qty:,.2f}")
        # Break down by unit when more than one unit is used
        by_unit: dict[str, float] = {}
        for it in inv.get("items") or []:
            u = (it.get("unit") or "").strip() or "—"
            by_unit[u] = by_unit.get(u, 0.0) + float(it.get("quantity") or 0)
        if len(by_unit) > 1:
            parts = [f"{escape(u)}: {q:,.2f}" for u, q in sorted(by_unit.items(), key=lambda x: x[0])]
            totals.append(f"<b>Qty by Unit:</b> {' · '.join(parts)}")
    if total_wt > 0.0005:
        totals.append(f"<b>Total Item Weight:</b> {total_wt:,.3f} kg")
    if inv.get("notes"):
        totals.append(f"<b>Notes:</b> {escape(str(inv['notes']))}")
    if totals:
        body += _totals_block(totals)
    body += signature_block_html(doc_label="sales order")
    return _wrap_doc(
        body, inv["document_no"], page_mode="full",
        user_id=document_preparer_user_id(inv),
    )


def _pdf_latin1(text) -> str:
    """FPDF core fonts need Latin-1; replace common Unicode punctuation."""
    if text is None:
        return ""
    s = str(text)
    for a, b in (
        ("\u2014", "-"), ("\u2013", "-"), ("\u2018", "'"), ("\u2019", "'"),
        ("\u201c", '"'), ("\u201d", '"'), ("\u00a0", " "), ("\u2022", "*"),
        ("Rs.", "Rs."), ("—", "-"), ("–", "-"),
    ):
        s = s.replace(a, b)
    return s.encode("latin-1", "replace").decode("latin-1")


