def _scraped_html_pdf_bytes(html: str, title: str, *, include_company: bool = True) -> bytes:
    """Fallback PDF from HTML text (sanitized for FPDF Latin-1)."""
    from fpdf import FPDF
    import re

    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=12)
    pdf.add_page()
    pdf.set_margins(12, 12, 12)
    usable = pdf.w - pdf.l_margin - pdf.r_margin
    if include_company:
        co = get_company_info()
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(usable, 7, _pdf_latin1(co.get("name") or ""), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "B", 11)
    pdf.cell(usable, 6, _pdf_latin1(title), new_x="LMARGIN", new_y="NEXT")
    prep = resolve_preparer_name()
    if prep:
        pdf.set_font("Helvetica", size=8)
        pdf.cell(usable, 5, _pdf_latin1(f"Generated by: {prep}"), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(2)
    pdf.set_font("Helvetica", size=8)
    text = html or ""
    text = re.sub(r"<style[\s\S]*?</style>", " ", text, flags=re.I)
    text = re.sub(r"<script[\s\S]*?</script>", " ", text, flags=re.I)
    text = re.sub(r"@page\s*\{[\s\S]*?\}", " ", text, flags=re.I)
    text = re.sub(r"<br\s*/?>", "\n", text, flags=re.I)
    text = re.sub(r"</tr>", "\n", text, flags=re.I)
    text = re.sub(r"<[^>]+>", " ", text)
    text = re.sub(r"[ \t]+", " ", text)
    for raw in text.split("\n"):
        clean = _pdf_latin1(raw.strip())
        if len(clean) < 2:
            continue
        # Chunk long lines so multi_cell never overflows
        while clean:
            chunk, clean = clean[:180], clean[180:]
            try:
                pdf.multi_cell(usable, 4, chunk)
            except Exception:
                pdf.cell(usable, 4, chunk[:90], new_x="LMARGIN", new_y="NEXT")
    return bytes(pdf.output())


